// ListRuleSets finds all ruleset files in the given directory.
func ListRuleSets(dir string) ([]string, error) {
	dir = utils.ExpandHome(dir)
	
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, nil
		}
		return nil, fmt.Errorf("reading directory %q: %w", dir, err)
	}
	
	var files []string
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if strings.HasSuffix(name, ".yaml") || strings.HasSuffix(name, ".yml") {
			files = append(files, filepath.Join(dir, name))
		}
	}
	
	return files, nil
}

// FindRuleSet searches for a ruleset by name in common locations.
func FindRuleSet(name string) (string, error) {
	// Try exact path first
	if _, err := os.Stat(name); err == nil {
		return name, nil
	}
	
	// Try with extensions
	for _, ext := range []string{".yaml", ".yml", ".rules.yaml", ".rules.yml"} {
		path := name + ext
		if _, err := os.Stat(path); err == nil {
			return path, nil
		}
	}
	
	// Try in ~/.doublebook/rules/
	home, _ := os.UserHomeDir()
	rulesDir := filepath.Join(home, ".doublebook", "rules")
	
	for _, ext := range []string{".yaml", ".yml", ".rules.yaml", ".rules.yml"} {
		path := filepath.Join(rulesDir, name+ext)
		if _, err := os.Stat(path); err == nil {
			return path, nil
		}
	}
	
	return "", fmt.Errorf("ruleset %q not found", name)
}

// DefaultRulesDir returns the default directory for ruleset files.
func DefaultRulesDir() string {
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".doublebook", "rules")
}
